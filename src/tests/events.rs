use netlink_packet_core::{Emitable, NetlinkMessage, NetlinkPayload};

use crate::AuditMessage;

use super::header;

#[test]
fn test_event_syscall() {
    let expected = NetlinkMessage::new(
        header(280, 1300, 0, 0),
        NetlinkPayload::from(AuditMessage::Event((
            1300,
            String::from_utf8_lossy(&EVENT_SYSCALL_BYTES[16..]).into(),
        ))),
    );

    assert_eq!(
        NetlinkMessage::<AuditMessage>::deserialize(EVENT_SYSCALL_BYTES)
            .unwrap(),
        expected
    );

    let mut buffer = Vec::new();
    expected.emit(&mut buffer).unwrap();
    assert_eq!(buffer.as_slice(), &EVENT_SYSCALL_BYTES[..]);
}

