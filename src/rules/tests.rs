fn watch_syscalls() -> RuleSyscalls {
    // The kernel reports old-style watch rules with the last syscall word
    // partially set (0x0000ffff instead of 0xffffffff).
    let mut syscalls = RuleSyscalls::new_maxed();
    for syscall in 2032..2048 {
        syscalls.unset(syscall);
    }
    syscalls
}

